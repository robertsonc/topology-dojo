/**
 * Build the font module the server-side rasterizer embeds.
 *
 *   npx tsx scripts/build-export-fonts.ts
 *
 * resvg (src/export/raster.ts) has no system fonts in a Worker and reads only
 * TrueType/OpenType, while @fontsource ships WOFF. This decodes the JetBrains
 * Mono latin + latin-ext WOFF (v1) subsets back to sfnt and writes them as
 * base64 into `src/export/fonts.generated.ts`, so Node, Vitest and the Worker
 * all load the same bytes with no file-system or bundler rule.
 *
 * JetBrains Mono is licensed under the SIL Open Font License 1.1 (see
 * node_modules/@fontsource/jetbrains-mono/LICENSE); embedding is permitted.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { unzlibSync } from 'fflate';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const files = path.join(root, 'node_modules/@fontsource/jetbrains-mono/files');
const out = path.join(root, 'src/export/fonts.generated.ts');

const FACES = [
  'latin-400-normal',
  'latin-700-normal',
  'latin-ext-400-normal',
  'latin-ext-700-normal',
];

/** Decode a WOFF 1.0 container to the sfnt (TTF/OTF) it wraps. */
export function woffToSfnt(woff: Uint8Array): Uint8Array {
  const dv = new DataView(woff.buffer, woff.byteOffset, woff.byteLength);
  if (dv.getUint32(0) !== 0x774f4646) throw new Error('not a WOFF 1.0 file');
  const flavor = dv.getUint32(4);
  const numTables = dv.getUint16(12);
  const tables: { tag: number; checksum: number; data: Uint8Array }[] = [];
  for (let i = 0; i < numTables; i++) {
    const o = 44 + i * 20;
    const tag = dv.getUint32(o);
    const offset = dv.getUint32(o + 4);
    const compLength = dv.getUint32(o + 8);
    const origLength = dv.getUint32(o + 12);
    const checksum = dv.getUint32(o + 16);
    const raw = woff.subarray(offset, offset + compLength);
    const data = compLength < origLength ? unzlibSync(raw) : raw;
    if (data.length !== origLength)
      throw new Error(`table ${tag.toString(16)} decoded to the wrong length`);
    tables.push({ tag, checksum, data });
  }
  let entrySelector = 0;
  while (1 << (entrySelector + 1) <= numTables) entrySelector++;
  const searchRange = (1 << entrySelector) * 16;
  const headerLen = 12 + numTables * 16;
  let total = headerLen;
  for (const t of tables) total += (t.data.length + 3) & ~3;
  const sfnt = new Uint8Array(total);
  const sv = new DataView(sfnt.buffer);
  sv.setUint32(0, flavor);
  sv.setUint16(4, numTables);
  sv.setUint16(6, searchRange);
  sv.setUint16(8, entrySelector);
  sv.setUint16(10, numTables * 16 - searchRange);
  let offset = headerLen;
  tables.forEach((t, i) => {
    const o = 12 + i * 16;
    sv.setUint32(o, t.tag);
    sv.setUint32(o + 4, t.checksum);
    sv.setUint32(o + 8, offset);
    sv.setUint32(o + 12, t.data.length);
    sfnt.set(t.data, offset);
    offset += (t.data.length + 3) & ~3;
  });
  return sfnt;
}

function main(): void {
  const entries = FACES.map((face) => {
    const woff = readFileSync(path.join(files, `jetbrains-mono-${face}.woff`));
    const sfnt = woffToSfnt(new Uint8Array(woff));
    return `  // jetbrains-mono-${face}\n  '${Buffer.from(sfnt).toString('base64')}',`;
  });
  writeFileSync(
    out,
    `// GENERATED by scripts/build-export-fonts.ts — do not edit.\n` +
      `// JetBrains Mono (SIL Open Font License 1.1), latin + latin-ext,\n` +
      `// regular + bold, as base64 TrueType for the server-side rasterizer.\n` +
      `export const EXPORT_FONTS_BASE64: readonly string[] = [\n` +
      entries.join('\n') +
      `\n];\n`,
  );
  console.log(`wrote ${path.relative(root, out)}`);
}

main();
